"""Build command: regenerate models/SKQYACE010.step and .stl from the model.

Run with ``uv run build-model``. Outputs are written to a temporary directory,
checked, and only then moved into place, so a failed build never touches the
committed files.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
import tempfile
from pathlib import Path

import cadquery as cq

from skqyace010 import checks
from skqyace010 import model

BASENAME = "SKQYACE010"
STL_TOLERANCE = 0.01  # mm, linear deflection
STL_ANGULAR_TOLERANCE = 0.1  # rad
FIXED_TIMESTAMP = "2026-01-01T00:00:00"
STL_HEADER = b"SKQYACE010 generated by skqyace010.build"

_REPO_ROOT = Path(__file__).resolve().parents[2]

# FILE_NAME('name','time_stamp',('author'),('organization'),'preprocessor',
#           'originating_system','authorization');
_FILE_NAME_RE = re.compile(
    r"FILE_NAME\('(?P<name>[^']*)','[^']*',\([^)]*\),\([^)]*\),"
)
_ENTITY_RE = re.compile(r"^#(\d+) = (.*?);\n", re.M | re.S)
_NAUO_RE = re.compile(r"(NEXT_ASSEMBLY_USAGE_OCCURRENCE\()'\d+'")
_REF_RE = re.compile(r"#(\d+)")
# Entities OCCT appends for colours. It emits them in hash-map order, which
# changes from run to run, so they are put into a canonical order.
_STYLE_START = ("MECHANICAL_DESIGN_GEOMETRIC_PRESENTATION_REPRESENTATION", "STYLED_ITEM")


def _canonicalize_style_tail(data: str) -> str:
    """Sorts the trailing colour entities of a STEP DATA section canonically.

    Everything from the first presentation entity on is renumbered in the
    order of a structural key (the entity text, with references to other tail
    entities replaced by their own keys). Entities before it are untouched.
    """
    matches = list(_ENTITY_RE.finditer(data))
    if not matches or "".join(m.group(0) for m in matches) != data:
        raise checks.CheckError("unexpected STEP DATA section layout")
    entities = {int(m.group(1)): m.group(2) for m in matches}
    starts = [i for i, body in entities.items() if body.startswith(_STYLE_START)]
    if not starts:
        return data
    first = min(starts)
    tail = sorted(i for i in entities if i >= first)
    tail_set = set(tail)

    keys: dict[int, str] = {}

    def key(i: int) -> str:
        if i not in keys:
            keys[i] = ""  # guards against reference cycles
            keys[i] = _REF_RE.sub(
                lambda m: f"<{key(int(m.group(1)))}>"
                if int(m.group(1)) in tail_set
                else m.group(0),
                entities[i],
            )
        return keys[i]

    # Roots (tail entities no other tail entity refers to) are sorted by key;
    # the rest are numbered in depth-first visit order from those roots, so
    # structurally identical copies (e.g. a colour shared by two parts) are
    # still ordered deterministically.
    def refs(i: int) -> list[int]:
        return [
            int(r) for r in _REF_RE.findall(entities[i]) if int(r) in tail_set
        ]

    referenced = {r for i in tail for r in refs(i)}
    roots = sorted((i for i in tail if i not in referenced), key=lambda i: key(i))
    order: list[int] = []
    seen: set[int] = set()

    def visit(i: int) -> None:
        if i in seen:
            return
        seen.add(i)
        order.append(i)
        for r in refs(i):
            visit(r)

    for root in roots:
        visit(root)
    if len(order) != len(tail):
        raise checks.CheckError("could not order STEP colour entities")
    renumber = {old: first + n for n, old in enumerate(order)}

    def remap(body: str) -> str:
        return _REF_RE.sub(
            lambda m: f"#{renumber.get(int(m.group(1)), int(m.group(1)))}", body
        )

    out = {}
    for i, body in entities.items():
        out[renumber.get(i, i)] = remap(body)
    return "".join(f"#{i} = {out[i]};\n" for i in sorted(out))


def normalize_step(path: Path) -> None:
    """Pins the STEP header so identical geometry gives identical bytes."""
    text = path.read_text(encoding="utf-8")
    new, n = _FILE_NAME_RE.subn(
        f"FILE_NAME('{BASENAME}','{FIXED_TIMESTAMP}',(''),(''),",
        text.replace("\r\n", "\n"),
        count=1,
    )
    if n != 1:
        raise checks.CheckError("STEP header FILE_NAME not found")
    # OCCT numbers assembly occurrences from a process-wide counter.
    counter = iter(range(1, 1_000_000))
    new = _NAUO_RE.sub(lambda m: f"{m.group(1)}'{next(counter)}'", new)
    head, sep, rest = new.partition("DATA;\n")
    data, sep2, end = rest.partition("ENDSEC;\n")
    if not sep or not sep2:
        raise checks.CheckError("STEP DATA section not found")
    new = head + sep + _canonicalize_style_tail(data) + sep2 + end
    path.write_text(new, encoding="utf-8", newline="\n")


def normalize_stl(path: Path) -> None:
    """Replaces the 80-byte binary STL header with a fixed one."""
    data = bytearray(path.read_bytes())
    data[:80] = STL_HEADER.ljust(80, b" ")
    path.write_bytes(bytes(data))


def export(out_dir: Path) -> tuple[Path, Path]:
    """Builds, checks and writes the STEP and STL into ``out_dir``.

    Returns:
      The (step, stl) paths.

    Raises:
      checks.CheckError: if the model or an output fails a check. ``out_dir``
        is left unchanged in that case.
    """
    parts = model.parts()
    checks.check_parts(parts)
    checks.check_cover(parts)
    fused = model.fused()
    checks.check_envelope(checks.BBox.of_shape(fused.val()), "model")

    out_dir.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=".build-", dir=out_dir))
    try:
        step = tmp / f"{BASENAME}.step"
        stl = tmp / f"{BASENAME}.stl"
        model.assembly().export(str(step), exportType="STEP")
        normalize_step(step)
        cq.exporters.export(
            fused,
            str(stl),
            exportType="STL",
            tolerance=STL_TOLERANCE,
            angularTolerance=STL_ANGULAR_TOLERANCE,
            opt={"ascii": False},
        )
        normalize_stl(stl)
        checks.check_outputs(step, stl, n_parts=len(parts))

        final_step = out_dir / step.name
        final_stl = out_dir / stl.name
        os.replace(step, final_step)
        os.replace(stl, final_stl)
        return final_step, final_stl
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=_REPO_ROOT / "models",
        help="output directory (default: %(default)s)",
    )
    args = parser.parse_args(argv)
    try:
        step, stl = export(args.out_dir)
    except checks.CheckError as e:
        print(f"build-model: FAILED: {e}", file=sys.stderr)
        return 1
    except Exception as e:  # CadQuery/OCCT errors: report, keep outputs.
        print(f"build-model: FAILED: {type(e).__name__}: {e}", file=sys.stderr)
        return 1
    print(step)
    print(stl)
    return 0


if __name__ == "__main__":
    sys.exit(main())
